export const isValidNickname = (nickname: string) => {
  if (!nickname.trim()) return false;

  const normalized = nickname
    .normalize("NFC")
    .toLowerCase()
    .replace(/\s/g, "")
    .replace(/[^가-힣a-z0-9]/g, "");

  return !bannedWords.some((word) =>
    normalized.includes(word.normalize("NFC")),
  );
};
